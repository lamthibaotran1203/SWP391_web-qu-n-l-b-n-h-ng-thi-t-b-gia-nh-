CREATE SCHEMA IF NOT EXISTS app;

CREATE TABLE app.user_account (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(100),
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(10),
    role VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    email_verified_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ck_user_account_role
        CHECK (role IN ('CUSTOMER', 'STAFF', 'MANAGER')),
    CONSTRAINT ck_user_account_status
        CHECK (status IN ('PENDING_VERIFICATION', 'ACTIVE', 'INACTIVE')),
    CONSTRAINT ck_user_account_active_credentials
        CHECK (status <> 'ACTIVE' OR (password_hash IS NOT NULL AND email_verified_at IS NOT NULL)),
    CONSTRAINT ck_user_account_full_name_length
        CHECK (char_length(full_name) BETWEEN 2 AND 100),
    CONSTRAINT ck_user_account_phone
        CHECK (phone IS NULL OR phone ~ '^0[0-9]{9}$')
);

CREATE UNIQUE INDEX ux_user_account_email_lower
    ON app.user_account (lower(email));

CREATE INDEX ix_user_account_role_status
    ON app.user_account (role, status, user_id);
