-- Sales-order read model used by UC-18.
CREATE TABLE app.sales_order (
    sales_order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(32) NOT NULL,
    channel VARCHAR(20) NOT NULL,
    order_status VARCHAR(30) NOT NULL,
    payment_status VARCHAR(30) NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    customer_name VARCHAR(100) NOT NULL,
    customer_email VARCHAR(254),
    customer_phone VARCHAR(20),
    shipping_address VARCHAR(500),
    subtotal NUMERIC(14, 2) NOT NULL,
    discount_amount NUMERIC(14, 2) NOT NULL DEFAULT 0,
    shipping_fee NUMERIC(14, 2) NOT NULL DEFAULT 0,
    total_amount NUMERIC(14, 2) NOT NULL,
    placed_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT ux_sales_order_order_number UNIQUE (order_number),
    CONSTRAINT ck_sales_order_channel
        CHECK (channel IN ('ONLINE', 'IN_STORE')),
    CONSTRAINT ck_sales_order_status
        CHECK (order_status IN (
            'PENDING_PAYMENT', 'CONFIRMED', 'PROCESSING', 'SHIPPED', 'DELIVERED', 'CANCELLED'
        )),
    CONSTRAINT ck_sales_order_payment_status
        CHECK (payment_status IN ('PENDING', 'PAID', 'FAILED', 'REFUNDED', 'COD')),
    CONSTRAINT ck_sales_order_payment_method
        CHECK (payment_method IN ('COD', 'CASH', 'CARD', 'BANK_TRANSFER', 'ONLINE_GATEWAY')),
    CONSTRAINT ck_sales_order_amounts
        CHECK (
            subtotal >= 0 AND discount_amount >= 0 AND shipping_fee >= 0
            AND total_amount >= 0
        )
);

CREATE INDEX ix_sales_order_placed_at
    ON app.sales_order (placed_at DESC, sales_order_id DESC);

CREATE INDEX ix_sales_order_channel_status_date
    ON app.sales_order (channel, order_status, placed_at DESC);

CREATE INDEX ix_sales_order_payment_status_date
    ON app.sales_order (payment_status, placed_at DESC);

CREATE TABLE app.sales_order_item (
    sales_order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id BIGINT NOT NULL REFERENCES app.sales_order (sales_order_id) ON DELETE CASCADE,
    product_name VARCHAR(150) NOT NULL,
    product_sku VARCHAR(64) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(14, 2) NOT NULL,
    line_total NUMERIC(14, 2) NOT NULL,
    CONSTRAINT ck_sales_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_sales_order_item_amounts CHECK (unit_price >= 0 AND line_total >= 0)
);

CREATE INDEX ix_sales_order_item_order
    ON app.sales_order_item (sales_order_id, sales_order_item_id);
