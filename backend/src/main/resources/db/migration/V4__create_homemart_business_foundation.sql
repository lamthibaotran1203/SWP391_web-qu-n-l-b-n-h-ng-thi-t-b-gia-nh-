CREATE TABLE app.hm_cart (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    sku_id bigint NOT NULL,
    quantity integer NOT NULL,
    created_by varchar(255),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by varchar(255),
    updated_at TIMESTAMPTZ,
    CONSTRAINT uq_cart_user_sku UNIQUE (user_id, sku_id),
    CONSTRAINT ck_cart_quantity CHECK (quantity > 0)
);

CREATE TABLE app.hm_order (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NULL,
    order_code varchar(50) NOT NULL UNIQUE,
    order_type varchar(50) NOT NULL,
    status varchar(50) NOT NULL,
    payment_status varchar(50) NOT NULL,
    total_amount numeric(18,0) NOT NULL,
    discount_amount numeric(18,0) NOT NULL DEFAULT 0,
    shipping_fee numeric(18,0) NOT NULL DEFAULT 0,
    final_amount numeric(18,0) NOT NULL,
    reservation_expiry TIMESTAMPTZ,
    note varchar(500),
    created_by varchar(255),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by varchar(255),
    updated_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    cancelled_at TIMESTAMPTZ,
    cancellation_reason VARCHAR(500),
    submission_key VARCHAR(255) UNIQUE,
    CONSTRAINT ck_order_channel CHECK (order_type IN ('ONLINE','COUNTER')),
    CONSTRAINT ck_order_customer CHECK (order_type <> 'ONLINE' OR user_id IS NOT NULL),
    CONSTRAINT ck_order_amounts CHECK (total_amount >= 0 AND discount_amount >= 0 AND shipping_fee >= 0 AND final_amount >= 0),
    CONSTRAINT ck_order_final_amount CHECK (final_amount = total_amount - discount_amount + shipping_fee)
);

CREATE TABLE app.hm_payment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    transaction_code varchar(100) NOT NULL UNIQUE,
    idempotency_key varchar(255) NOT NULL UNIQUE,
    amount numeric(18,0) NOT NULL,
    payment_method varchar(50) NOT NULL,
    status varchar(50) NOT NULL,
    payment_time TIMESTAMPTZ,
    created_by varchar(255),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by varchar(255),
    updated_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    provider VARCHAR(50) NOT NULL CHECK (btrim(provider) <> ''),
    gateway_transaction_id VARCHAR(100),
    reconciliation_reason VARCHAR(500),
    CONSTRAINT uq_payment_provider_ref UNIQUE (provider, gateway_transaction_id),
    CONSTRAINT uq_payment_order_identity UNIQUE (id, order_id),
    CONSTRAINT ck_payment_status CHECK (status IN ('PENDING','COMPLETED','FAILED')),
    CONSTRAINT ck_payment_amount CHECK (amount >= 0),
    CONSTRAINT ck_payment_settlement CHECK (status <> 'COMPLETED' OR payment_time IS NOT NULL)
);

