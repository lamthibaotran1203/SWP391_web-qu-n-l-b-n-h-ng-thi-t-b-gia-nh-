-- Completed financial evidence and historical events cannot be changed or erased.
-- Pending/failed logical attempts remain mutable for retries/status processing.
CREATE FUNCTION app.reject_history_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Historical records are immutable' USING ERRCODE = '23514';
END;
$$;
CREATE FUNCTION app.protect_completed_financial_record() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' OR OLD.status = 'COMPLETED' THEN
        RAISE EXCEPTION 'Financial records cannot be deleted or completed evidence changed' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER immutable_payment_history BEFORE UPDATE OR DELETE ON app.hm_payment
    FOR EACH ROW EXECUTE FUNCTION app.protect_completed_financial_record();
CREATE TRIGGER immutable_refund_history BEFORE UPDATE OR DELETE ON app.hm_refund
    FOR EACH ROW EXECUTE FUNCTION app.protect_completed_financial_record();
CREATE TRIGGER immutable_stock_movement BEFORE UPDATE OR DELETE ON app.hm_stock_movement
    FOR EACH ROW EXECUTE FUNCTION app.reject_history_mutation();
CREATE TRIGGER immutable_stock_adjustment BEFORE UPDATE OR DELETE ON app.hm_stock_adjustment
    FOR EACH ROW EXECUTE FUNCTION app.reject_history_mutation();
CREATE TRIGGER immutable_callback_event BEFORE UPDATE OR DELETE ON app.hm_payment_callback_event
    FOR EACH ROW EXECUTE FUNCTION app.reject_history_mutation();
CREATE TRIGGER immutable_order_event BEFORE UPDATE OR DELETE ON app.hm_order_status_event
    FOR EACH ROW EXECUTE FUNCTION app.reject_history_mutation();

-- Preserve imported catalogue data and make incomplete items unpublished.
-- category/brand names are backfilled only where they actually exist.
INSERT INTO app.hm_category(code, name, created_by, created_at)
SELECT 'LEGACY_CAT_' || md5(lower(btrim(category))), min(btrim(category)),
       'MIGRATION_V4', CURRENT_TIMESTAMP
FROM app.product WHERE NULLIF(btrim(category), '') IS NOT NULL
GROUP BY lower(btrim(category));
INSERT INTO app.hm_brand(name, created_by, created_at)
SELECT min(btrim(brand)), 'MIGRATION_V4', CURRENT_TIMESTAMP
FROM app.product WHERE NULLIF(btrim(brand), '') IS NOT NULL
GROUP BY lower(btrim(brand));
UPDATE app.product p SET category_id = c.id
FROM app.hm_category c WHERE lower(btrim(p.category)) = lower(btrim(c.name));
UPDATE app.product p SET brand_id = b.id
FROM app.hm_brand b WHERE lower(btrim(p.brand)) = lower(btrim(b.name));
UPDATE app.product SET status = 'INACTIVE'
WHERE status = 'ACTIVE' AND (category_id IS NULL OR brand_id IS NULL
    OR NULLIF(btrim(image_url), '') IS NULL);
ALTER TABLE app.product ADD CONSTRAINT ck_product_publication CHECK (
    status <> 'ACTIVE' OR (NOT is_deleted AND category_id IS NOT NULL AND brand_id IS NOT NULL
        AND NULLIF(btrim(image_url), '') IS NOT NULL));

-- Legacy SKU labels become internal store barcode values, not manufacturer EANs.
INSERT INTO app.hm_sku(product_id, sku_code, barcode, sku_name, image_url,
                       original_price, selling_price, status, created_by, created_at)
SELECT product_id, sku, sku, name, image_url, price, price, status,
       'MIGRATION_V4', CURRENT_TIMESTAMP FROM app.product;
INSERT INTO app.hm_inventory(sku_id, physical_quantity, reserved_quantity, created_by, created_at)
SELECT s.id, p.stock_quantity, 0, 'MIGRATION_V4', CURRENT_TIMESTAMP
FROM app.product p JOIN app.hm_sku s ON s.product_id = p.product_id;
INSERT INTO app.hm_stock_movement(sku_id, movement_type, quantity_change, balance_after,
                                 reference_type, reference_id, movement_date,
                                 created_by, created_at, posting_key)
SELECT s.id, 'OPENING_BALANCE', p.stock_quantity, p.stock_quantity,
       'LEGACY_PRODUCT', p.product_id, CURRENT_TIMESTAMP,
       'MIGRATION_V4', CURRENT_TIMESTAMP, 'V4_OPENING_PRODUCT_' || p.product_id
FROM app.product p JOIN app.hm_sku s ON s.product_id = p.product_id
WHERE p.stock_quantity > 0;
