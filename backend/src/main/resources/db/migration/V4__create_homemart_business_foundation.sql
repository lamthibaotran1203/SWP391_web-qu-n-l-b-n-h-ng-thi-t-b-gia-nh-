    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id bigint NOT NULL,
    sku_id bigint NOT NULL,
    ordered_quantity integer NOT NULL,
    received_quantity integer NOT NULL DEFAULT 0,
    unit_cost numeric(18,0) NOT NULL,
    created_by varchar(255),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by varchar(255),
    updated_at TIMESTAMPTZ,
    CONSTRAINT uq_po_sku UNIQUE (po_id, sku_id),
    CONSTRAINT uq_po_item_identity UNIQUE (id, po_id, sku_id),
    CONSTRAINT ck_po_item_quantities CHECK (ordered_quantity > 0 AND received_quantity >= 0 AND received_quantity <= ordered_quantity),
    CONSTRAINT ck_po_item_cost CHECK (unit_cost >= 0)
);

CREATE TABLE app.hm_return_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_request_id bigint NOT NULL,
    sku_id bigint NOT NULL,
    requested_quantity integer NOT NULL,
    condition_status varchar(50) NOT NULL,
    refund_amount numeric(18,0) NOT NULL,
    created_by varchar(255),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by varchar(255),
    updated_at TIMESTAMPTZ,
    order_id BIGINT NOT NULL,
    order_item_id BIGINT NOT NULL,
    approved_quantity INTEGER NOT NULL DEFAULT 0,
    restocked_quantity INTEGER NOT NULL DEFAULT 0,
    inspected_by BIGINT,
    inspected_at TIMESTAMPTZ,
    inspection_note VARCHAR(1000),
    evidence_url VARCHAR(512),
    recommendation VARCHAR(500),
    CONSTRAINT uq_return_order_line UNIQUE (return_request_id, order_item_id),
    CONSTRAINT ck_return_quantities CHECK (requested_quantity > 0 AND approved_quantity BETWEEN 0 AND requested_quantity AND restocked_quantity BETWEEN 0 AND approved_quantity),
    CONSTRAINT ck_return_line_amount CHECK (refund_amount >= 0),
    CONSTRAINT ck_return_condition CHECK (condition_status IN ('UNINSPECTED','RESALABLE','NON_RESALABLE')),
    CONSTRAINT ck_return_inspection CHECK (condition_status = 'UNINSPECTED' OR (inspected_by IS NOT NULL AND inspected_at IS NOT NULL)),
    CONSTRAINT ck_return_restock_condition CHECK (restocked_quantity = 0 OR condition_status = 'RESALABLE')
);

CREATE TABLE app.hm_inventory (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_id bigint NOT NULL UNIQUE,
    physical_quantity integer NOT NULL DEFAULT 0,
    reserved_quantity integer NOT NULL DEFAULT 0,
    available_quantity integer GENERATED ALWAYS AS (physical_quantity - reserved_quantity) STORED,
    last_inventory_date TIMESTAMPTZ,
    created_by varchar(255),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by varchar(255),
    updated_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    CONSTRAINT ck_inventory_balance CHECK (physical_quantity >= reserved_quantity AND reserved_quantity >= 0)
);

CREATE TABLE app.hm_stock_adjustment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_id bigint NOT NULL,
    system_quantity integer NOT NULL,
    actual_quantity integer NOT NULL,
    adjusted_quantity integer NOT NULL,
    reason varchar(500) NOT NULL,
    adjusted_by varchar(255) NOT NULL,
    adjusted_date TIMESTAMPTZ NOT NULL,
    created_by varchar(255),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by varchar(255),
    updated_at TIMESTAMPTZ,
    CONSTRAINT ck_adjustment_quantities CHECK (system_quantity >= 0 AND actual_quantity >= 0 AND adjusted_quantity = actual_quantity - system_quantity),
    CONSTRAINT ck_adjustment_reason CHECK (btrim(reason) <> '')
);

