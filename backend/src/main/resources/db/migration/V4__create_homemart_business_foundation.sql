    CONSTRAINT ck_return_decision CHECK (status NOT IN ('APPROVED','REJECTED') OR (decided_by IS NOT NULL AND decided_at IS NOT NULL)),
    CONSTRAINT ck_return_rejection_reason CHECK (status <> 'REJECTED' OR NULLIF(btrim(decision_reason), '') IS NOT NULL)
