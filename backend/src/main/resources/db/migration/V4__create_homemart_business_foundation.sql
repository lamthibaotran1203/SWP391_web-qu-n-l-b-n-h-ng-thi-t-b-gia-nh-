CREATE TABLE app.hm_order_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id bigint NOT NULL,
    sku_id bigint NOT NULL,
    quantity integer NOT NULL,
    unit_price numeric(18,0) NOT NULL,
    total_price numeric(18,0) NOT NULL,
    created_by varchar(255),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by varchar(255),
    updated_at TIMESTAMPTZ,
    sku_code_snapshot VARCHAR(100) NOT NULL,
    sku_name_snapshot VARCHAR(255) NOT NULL,
    discount_amount NUMERIC(18,0) NOT NULL DEFAULT 0,
    CONSTRAINT uq_order_item_identity UNIQUE (id, order_id, sku_id),
    CONSTRAINT ck_order_item_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_item_amounts CHECK (unit_price >= 0 AND total_price >= 0 AND discount_amount >= 0 AND discount_amount <= total_price),
    CONSTRAINT ck_order_item_total CHECK (total_price = unit_price * quantity)
);

