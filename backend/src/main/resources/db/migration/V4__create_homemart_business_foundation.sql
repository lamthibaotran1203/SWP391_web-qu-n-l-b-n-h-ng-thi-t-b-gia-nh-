-- V4: schema foundation derived from supplied HomeMart diagram, corrected for the
-- 2026-10-05 user decisions recorded in the canonical Backlog column I.
-- Sole identity remains V1 app.user_account. No accounts/demo data are seeded.
-- Extra shared tables are integration prerequisites, not completed teammate UCs.
-- Business permissions, cumulative quantity/balance limits and state transitions
-- remain authoritative service responsibilities and must run in transactions.
-- Flyway manages the migration transaction. Do not paste this into SQL Editor.
CREATE TABLE app.hm_address (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    recipient_name varchar(255) NOT NULL,
    recipient_phone varchar(50) NOT NULL,
    province varchar(255) NOT NULL,
    district varchar(255) NOT NULL,
    ward varchar(255) NOT NULL,
    street_address varchar(500) NOT NULL,
    is_default boolean NOT NULL DEFAULT false,
    is_deleted boolean NOT NULL DEFAULT false,
    created_by varchar(255),
    created_at TIMESTAMPTZ NOT NULL,
    updated_by varchar(255),
    updated_at TIMESTAMPTZ,
    CONSTRAINT ck_address_deleted_default CHECK (NOT is_deleted OR NOT is_default)
);

CREATE TABLE app.hm_supplier (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
